export function dictionaryFor(lang) {
  const i = IDX[lang];
  if (!i) return null;
  const dict = Object.fromEntries(ROWS.map((r) => [r[0], r[i]]));
  const u = UNITS[lang];
  const pick = (n, pair) => (n === "1" ? pair[0] : pair[1]);
  const patterns = [
    [/^(\d[\d,.]*K?) (member|members)$/, (n) => `${n} ${pick(n, u.member)}`],
    [/^(\d[\d,.]*K?) (reply|replies)$/, (n) => `${n} ${pick(n, u.reply)}`],
    [/^(\d[\d,.]*K?) (view|views)$/, (n) => `${n} ${pick(n, u.view)}`],
    [/^(\d[\d,.]*K?) online$/, (n) => `${n} ${u.online}`],
    [/^(\d[\d,.]*K?) (person|people) going$/, (n) => `${n} ${u.going}`],
  ];
  return [dict, patterns];
}
